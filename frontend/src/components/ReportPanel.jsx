import { FileText, Loader2 } from 'lucide-react';
import Markdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

function ReportBody({ status, report }) {
  switch (status) {
    case 'completed':
      return (
        <div className="markdown">
          <Markdown remarkPlugins={[remarkGfm]}>{report}</Markdown>
        </div>
      );
    case 'pending':
      return (
        <p className="muted report-status">
          <Loader2 size={16} className="spin" aria-hidden="true" /> Generating analyst report…
        </p>
      );
    case 'skipped':
      return (
        <p className="muted report-status">
          LLM reporting is not configured on this server (no GEMINI_API_KEY). The verdict and
          indicators above are unaffected.
        </p>
      );
    case 'failed':
      return (
        <p className="warning-text report-status">
          The LLM report could not be generated after several retries. The verdict and indicators
          above are unaffected.
        </p>
      );
    default:
      return <p className="muted report-status">No report.</p>;
  }
}

export default function ReportPanel({ status, report }) {
  return (
    <div className="nexus-card">
      <h3 className="card-title">
        <FileText size={16} className="accent-red" aria-hidden="true" /> GenAI threat intelligence report
      </h3>
      <p className="card-caption">
        Generated by an LLM from the indicators and SHAP values. Verify before acting on it.
      </p>
      <div className="report-wrapper" aria-live="polite">
        <ReportBody status={status} report={report} />
      </div>
    </div>
  );
}
